#!/usr/bin/env python3
"""Generate rust/rime/src/key_table_data.rs from the C++ key_table.cc.

This is a one-shot migration aid: it parses the original librime C source and
emits an equivalent, self-contained Rust static table. Run it once; commit the
generated .rs file so the Rust crate no longer depends on the C sources.
"""
import json
import re
import sys
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "src" / "rime" / "key_table.cc"
OUT = ROOT / "rust" / "rime" / "src" / "key_table_data.rs"

def unescape_c(s: str) -> str:
    out = bytearray()
    i = 0
    while i < len(s):
        c = s[i]
        if c == "\\" and i + 1 < len(s):
            n = s[i + 1]
            if n == "0":
                out.append(0); i += 2; continue
            if n in "01234567":
                j = i + 1; num = 0
                while j < len(s) and j < i + 4 and s[j] in "01234567":
                    num = num * 8 + int(s[j]); j += 1
                out.append(num & 0xFF); i = j; continue
            if n == "n":
                out.append(10); i += 2; continue
            if n == "t":
                out.append(9); i += 2; continue
            if n == "r":
                out.append(13); i += 2; continue
            if n == '"':
                out.append(0x22); i += 2; continue
            if n == "\\":
                out.append(0x5C); i += 2; continue
            out.append(ord(n)); i += 2; continue
        out.append(ord(c)); i += 1
    return out.decode("latin-1")

def rust_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)

def main() -> None:
    text = SRC.read_text(encoding="utf-8")

    # --- modifier_name[] --- parse every string literal and NULL in order
    m = re.search(r"static const char\* modifier_name\[\] = \{(.*?)\};", text, re.S)
    if not m:
        print("modifier_name array not found"); sys.exit(1)
    mod_names: list = []
    for match in re.finditer(r'"((?:[^"\\]|\\.)*)"|NULL', m.group(1)):
        if match.group(0) == "NULL":
            mod_names.append(None)
        else:
            mod_names.append(unescape_c(match.group(1)))
    while len(mod_names) < 32:
        mod_names.append(None)
    mod_names = mod_names[:32]

    # --- key_names[] ---
    m = re.search(r"static const char key_names\[\] =(.*?);", text, re.S)
    if not m:
        print("key_names not found"); sys.exit(1)
    literals = re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(1))
    blob = "".join(unescape_c(l) for l in literals)
    names: list[str] = [p for p in blob.split("\x00") if p != ""]
    off = 0
    offset_to_idx: dict[int, int] = {}
    for idx, name in enumerate(names):
        offset_to_idx[off] = idx
        off += len(name) + 1

    # --- keys_by_keyval[] ---
    m = re.search(r"static const key_entry keys_by_keyval\[\] = \{(.*?)\};", text, re.S)
    if not m:
        print("keys_by_keyval not found"); sys.exit(1)
    entries = re.findall(r"\{0x([0-9a-fA-F]+),\s*(\d+)\}", m.group(1))
    by_keyval: list[tuple[int, int]] = []
    for keyval_s, offset_s in entries:
        keyval = int(keyval_s, 16)
        offset = int(offset_s)
        idx = offset_to_idx.get(offset)
        if idx is None:
            print(f"warning: offset {offset} not found for keyval 0x{keyval:x}"); continue
        by_keyval.append((keyval, idx))

    # --- emit ---
    lines = []
    lines.append("// @generated by rust/tools/gen_key_table.py — do not edit by hand.")
    lines.append("// Derived from the X11 keysym table in the original librime C++ sources.")
    lines.append("")
    lines.append("pub const MODIFIER_NAMES: [Option<&'static str>; 32] = [")
    for i, nm in enumerate(mod_names):
        if nm is not None:
            lines.append(f"    Some({rust_str(nm)}), // {i}")
        else:
            lines.append(f"    None, // {i}")
    lines.append("];")
    lines.append("")
    lines.append("pub const KEY_NAMES: &[&'static str] = &[")
    for nm in names:
        lines.append(f"    {rust_str(nm)},")
    lines.append("];")
    lines.append("")
    lines.append("pub const KEYS_BY_KEYVAL: &[(u32, usize)] = &[")
    for keyval, idx in by_keyval:
        lines.append(f"    (0x{keyval:x}, {idx}),")
    lines.append("];")
    lines.append("")

    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} ({len(names)} key names, {len(by_keyval)} keyval entries)")

if __name__ == "__main__":
    main()
